// swift-tools-version:5.10
import PackageDescription

// The core's version. scripts/update-core.sh <version> changes it, the checksum and the vendored
// UniFFI source together.
let coreVersion = "1.0.0"
let coreChecksum = "20f3576588ac06614af16d9ca0d0b108f51a37bc0548def187d15b74c210be24"

let package = Package(
    name: "openvireo-examples-swift",
    platforms: [.macOS(.v13)],
    targets: [
        // The Rust core, built for iOS, the iOS simulator and macOS, from the GitHub release
        .binaryTarget(
            name: "OpenVireoRustCoreFFI",
            url: "https://github.com/openvireo/openvireo-core/releases/download/v\(coreVersion)/OpenVireoCore.xcframework.zip",
            checksum: coreChecksum),
        // The Swift API over it: OpenVireoRustCore.swift from the same release, as generated by UniFFI
        .target(
            name: "OpenVireoRustCore",
            dependencies: ["OpenVireoRustCoreFFI"],
            swiftSettings: [.unsafeFlags(["-suppress-warnings"])],
            linkerSettings: [.linkedFramework("Security"), .linkedFramework("SystemConfiguration")]),
        .executableTarget(
            name: "Examples",
            dependencies: ["OpenVireoRustCore"]),
    ]
)
